# Train the candidate chooser (13 features -> 16 ReLU -> 1 score, softmax across the 3 candidates)
# on train.npz, report on val.npz, write src/vision/samChooserWeights.ts. Pure numpy.
import sys, json, numpy as np
rng = np.random.default_rng(0)
tr, va = np.load("train.npz"), np.load("val.npz")
Xtr, Ytr, Xva, Yva = tr["X"], tr["Y"], va["X"], va["Y"]
mean = Xtr.reshape(-1, Xtr.shape[2]).mean(0); std = Xtr.reshape(-1, Xtr.shape[2]).std(0) + 1e-6
mean[-3:], std[-3:] = 0, 1  # keep slot one-hots as is
nrm = lambda X: (X - mean) / std
H = int(sys.argv[1]) if len(sys.argv) > 1 else 16
W1 = rng.normal(0, 0.3, (H, Xtr.shape[2])); b1 = np.zeros(H); W2 = rng.normal(0, 0.3, H); b2 = 0.0
params = [W1, b1, W2]
def forward(X):
    A = X @ W1.T + b1; R = np.maximum(A, 0); return A, R, R @ W2 + b2
def picked(X, Y):
    s = forward(nrm(X))[2]; return Y[np.arange(len(Y)), s.argmax(1)].mean()
m = [np.zeros_like(p) for p in params]; v = [np.zeros_like(p) for p in params]
Xn = nrm(Xtr); T = np.exp(Ytr * 12); T /= T.sum(1, keepdims=True)
lr, l2, best = 3e-3, 1e-4, (-1, None)
for ep in range(300):
    perm = rng.permutation(len(Xn))
    for i in range(0, len(perm), 256):
        b = perm[i : i + 256]; X, Tt = Xn[b], T[b]
        A, R, S = forward(X)
        P = np.exp(S - S.max(1, keepdims=True)); P /= P.sum(1, keepdims=True)
        dS = (P - Tt) / len(b)                           # [n,3]
        gW2 = np.einsum("nc,nch->h", dS, R)
        dA = dS[..., None] * W2 * (A > 0)                # [n,3,H]
        gW1 = np.einsum("nch,ncf->hf", dA, X); gb1 = dA.sum((0, 1))
        for k, (p, g) in enumerate(zip(params, [gW1 + l2 * W1, gb1, gW2 + l2 * W2])):
            m[k] = 0.9 * m[k] + 0.1 * g; v[k] = 0.999 * v[k] + 0.001 * g * g
            p -= lr * m[k] / (np.sqrt(v[k]) + 1e-8)
    if ep % 20 == 19:
        t, s = picked(Xtr, Ytr), picked(Xva, Yva); print(f"epoch {ep+1} train {t:.3f} val {s:.3f}", flush=True)
        if t > best[0]: best = (t, [p.copy() for p in params])  # select on TRAIN only; val stays untouched
W1, b1, W2 = best[1]; params = [W1, b1, W2]
sam = lambda Y, X: Y[np.arange(len(Y)), X[:, :, 0].argmax(1)].mean()
print(f"VAL (Open Images val, never used for training or selection): SAM argmax {sam(Yva, Xva):.3f} -> chooser {picked(Xva, Yva):.3f} (oracle {Yva.max(1).mean():.3f})")
r = lambda a: [round(float(x), 6) for x in np.ravel(a)]
ts = f"""// Generated by scripts/chooser/train.py from Open Images train masks; see samChooser.ts.
// Val (Open Images val, 400 objects x 2 clicks): SAM's own pick {sam(Yva, Xva):.3f} mIoU -> chooser {picked(Xva, Yva):.3f} (best possible {Yva.max(1).mean():.3f}).
export const CHOOSER: {{ mean: number[]; std: number[]; w1: number[][]; b1: number[]; w2: number[]; b2: number }} | null = {json.dumps(dict(mean=r(mean), std=r(std), w1=[r(w) for w in W1], b1=r(b1), w2=r(W2), b2=0.0))};
"""
open("/home/user/reality/src/vision/samChooserWeights.ts", "w").write(ts)
